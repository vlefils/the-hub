// Static catalogue. The single player is hosted outside the book sections.
import { access, readFile, writeFile } from 'node:fs/promises';
import { musicPlaylist as playlist } from '../data/music.mjs';
const escape = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
const duration = seconds => `${Math.floor(seconds / 60)}:${String(Math.floor(seconds % 60)).padStart(2, '0')}`;
const minutes = Math.round(playlist.tracks.reduce((sum, track) => sum + track.duration, 0) / 60);
if (!playlist.tracks.length) throw new Error('Add at least one song to data/music.mjs before building the page.');
for (const track of playlist.tracks) {
  if (!track.audio?.startsWith('assets/music/audio/')) throw new Error(`Missing audio path: ${track.title}`);
  await access(new URL(`../${track.audio}`, import.meta.url));
}
const summary = `${playlist.tracks.length} morceaux · ${Math.floor(minutes / 60)} h ${String(minutes % 60).padStart(2, '0')} min`;
const songs = playlist.tracks.map((track, index) => `                <li>
                  <a class="music-track" href="${escape(track.audio)}" data-music-track="${escape(track.id)}">
                    <span class="music-track-number" aria-hidden="true">${String(index + 1).padStart(2, '0')}</span>
                    <span class="music-track-copy"><strong data-music-title translate="no">${escape(track.title)}</strong><small translate="no">${escape(track.style)}</small></span>
                    <span class="music-track-duration" translate="no">${duration(track.duration)}</span>
                  </a>
                </li>`).join('\n');
const page = `<!-- MUSIC:START — generated by tools/build-music.mjs -->
          <section class="page-section panel" id="outils-musique" data-section data-category="outils" data-reader-app>
            <div class="section-heading"><p class="section-kicker">Outils</p><div><h2>Musique</h2></div></div>
            <header class="music-intro">
              <img class="music-cover" src="${escape(playlist.cover)}" alt="Pochette de la playlist The Hub" width="1600" height="1600" loading="lazy" decoding="async" />
              <div class="music-intro-copy">
                <p class="music-eyebrow">Playlist · <span translate="no">${escape(playlist.creator)}</span></p>
                <h3 translate="no">${escape(playlist.title)}</h3>
                <p>Retrouvez l’univers de The Hub en musique et accompagnez vos parties.</p>
                <p class="music-summary">${summary}</p>
                <a class="overview-text-link" href="${escape(playlist.url)}" target="_blank" rel="noopener noreferrer">Écouter la playlist sur Suno <span aria-hidden="true">↗</span></a>
              </div>
            </header>
            <div class="music-listen">
              <button class="music-open" type="button" data-music-open hidden>Ouvrir le lecteur</button>
              <p data-music-state role="status">Le lecteur reste accessible en bas à droite sur tout le site.</p>
            </div>
            <div class="music-catalogue">
              <div class="music-list-heading"><h3>Les morceaux</h3><span>Durée</span></div>
              <noscript><p>Ouvrez un titre pour l’écouter dans votre navigateur.</p></noscript>
              <ol class="music-tracks" aria-label="Morceaux de la playlist The Hub">
${songs}
              </ol>
            </div>
          </section>
          <!-- MUSIC:END -->`;
const path = new URL('../index.html', import.meta.url);
const html = await readFile(path, 'utf8');
const marker = /<!-- MUSIC:START[^]*?<!-- MUSIC:END -->/;
if (!marker.test(html)) throw new Error('Music page insertion point not found.');
const host = `<iframe class="music-frame" data-music-frame data-mode="collapsed" title="Lecteur de musique" allow="autoplay" hidden></iframe>`;
const playerMarker = /<aside class="music-mini"[^]*?<\/aside>|<iframe class="music-frame"[^]*?<\/iframe>/;
if (!playerMarker.test(html)) throw new Error('Global player insertion point not found.');
await writeFile(path, html.replace(marker, page).replace(playerMarker, host));
console.log(`Music catalogue built: ${summary}. Global Pekly player retained.`);
