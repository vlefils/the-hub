await db.query('delete from auth.users where id=$1', [owner]);
assert.equal((await db.query('select count(*)::int as n from public.rb_solo_saves')).rows[0].n, 1, 'Le nettoyage du compte de test ne touche pas aux parties de l’autre compte.');
await db.close();
console.log('Solo SQL passed: additive migration, private permissions, account ownership, CAS, idempotency, deduplicated imports, size limit, reset and scoped account cleanup.');
