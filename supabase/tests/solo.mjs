assert.equal((await commit(owner, id, 1, state, updateId)).rows[0].saved.revision, 2, 'Réponse perdue : pas de deuxième écriture.');
await assert.rejects(() => commit(owner, id, 1, state), /RB_SOLO_CONFLICT/);
await assert.rejects(() => commit(other, id, 2, state), /RB_SOLO_NOT_FOUND/);
await assert.rejects(() => commit(other, crypto.randomUUID(), 0, state, crypto.randomUUID(), null, id), /RB_SOLO_NOT_FOUND/);
assert.equal((await db.query('select club_name,season,status from public.rb_solo_saves where id=$1', [id])).rows[0].club_name, 'Solo SQL');
const imported = crypto.randomUUID(), importKey = 'a'.repeat(64);
