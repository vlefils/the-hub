for (const role of ['anon', 'authenticated']) {
  await db.exec(`set role ${role}`);
  await assert.rejects(() => db.query('select state from public.rb_solo_saves'), /permission denied/);
  await assert.rejects(() => commit(owner, id, 0, state), /permission denied/);
  await db.exec('reset role');
}
await db.exec('set role service_role');
const write = crypto.randomUUID();
assert.equal((await commit(owner, id, 0, state, write)).rows[0].saved.revision, 1);
assert.equal((await commit(owner, id, 0, state, write)).rows[0].saved.revision, 1, 'Création réessayée sans doublon.');
