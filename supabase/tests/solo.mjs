import { pathToFileURL } from 'node:url';
import { createCareer } from '../../rumbleball/career.mjs';
const { PGlite } = await import(pathToFileURL(resolve(process.argv[2])));
const db = new PGlite();
await db.exec('create role anon; create role authenticated; create role service_role bypassrls; create schema auth; create table auth.users(id uuid primary key);');
const sql = await readFile(new URL('../migrations/20261019200000_rumbleball_solo.sql', import.meta.url), 'utf8');
await db.exec(sql); await db.exec(sql);
const owner = crypto.randomUUID(), other = crypto.randomUUID(), id = crypto.randomUUID(), state = createCareer('Solo SQL', 'solo-sql');
