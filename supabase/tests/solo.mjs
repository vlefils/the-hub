const duplicate = (await commit(owner, crypto.randomUUID(), 0, state, crypto.randomUUID(), importKey)).rows[0].saved;
assert.equal(duplicate.id, imported); assert.equal(duplicate.revision, 2); assert.equal(duplicate.alreadyImported, true);
assert.equal((await db.query('select club_name from public.rb_solo_saves where id=$1', [imported])).rows[0].club_name, 'Version récente');
